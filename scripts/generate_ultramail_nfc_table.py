#!/usr/bin/env python3
"""Generate Apps/UltraMail/engine/UltraMailNfcEscapeTable.h.

UltraMail caches each mail folder's messages in a directory named after the
folder (UltraMail::CacheDirectoryOf). macOS (APFS, HFS+) takes two names that
are canonically equivalent in Unicode - "u" + U+0308 and "ü" - as the same
name, so two folders spelled that way would share one directory.

Two different strings that are both in Normalization Form C are never
canonically equivalent. So CacheDirectoryOf writes every code point that
could keep a directory name from being NFC as an escape (~x and its code),
and every directory name it makes is NFC. Those code points are exactly the
ones the NFC quick check does not pass on their own (UAX #15):

  - NFC_Quick_Check=No: the character changes under NFC by itself
    (singletons such as the Ohm sign, composition exclusions);
  - NFC_Quick_Check=Maybe: the character may compose with the one before it
    (the second character of a canonical pair: combining marks, Indic vowel
    and length marks, Hangul medial vowels and final consonants);
  - Canonical_Combining_Class != 0: its order against its neighbours is
    canonical, so it is escaped as well and order never matters.

A string of the remaining characters passes the NFC quick check with YES,
which is definitive: it is in NFC.

Python's unicodedata has no NFC_Quick_Check property, so it is derived:
"No" as a character that NFC changes on its own, "Maybe" as the second
character of any two-character canonical decomposition (a superset of the
property: escaping more than needed is harmless).

Usage:
    python3 scripts/generate_ultramail_nfc_table.py          # write the header
    python3 scripts/generate_ultramail_nfc_table.py --check  # exit 1 if stale

CI (.github/workflows/ultramail-nfc-table.yml) runs --check on the Python the
table was made with whenever the table, this script or the code using it
changes, and once a week on the newest Python, which says when a new Unicode
version is out and the table is due to be regenerated.
"""
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Apps" / "UltraMail" / "engine" / "UltraMailNfcEscapeTable.h"


def escaped_code_points():
    second_of_pair = set()
    for cp in range(0x110000):
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith("<"):
            continue
        parts = d.split()
        if len(parts) == 2:
            second_of_pair.add(int(parts[1], 16))
    # Hangul: the medial vowels and final consonants compose algorithmically.
    second_of_pair.update(range(0x1161, 0x1176))
    second_of_pair.update(range(0x11A8, 0x11C3))

    out = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        if (unicodedata.combining(ch) != 0
                or unicodedata.normalize("NFC", ch) != ch
                or cp in second_of_pair):
            out.append(cp)
    return out


def ranges(cps):
    result = []
    for cp in cps:
        if result and result[-1][1] == cp - 1:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return result


def render():
    rs = ranges(escaped_code_points())
    lines = [
        "// Apps/UltraMail/engine/UltraMailNfcEscapeTable.h",
        "// GENERATED by scripts/generate_ultramail_nfc_table.py from Unicode "
        + unicodedata.unidata_version + " - do not edit.",
        "// The code points UltraMail::CacheDirectoryOf writes as ~x escapes so that",
        "// every cache directory name is in Unicode Normalization Form C: those whose",
        "// NFC_Quick_Check is No or Maybe, and every one with a non-zero canonical",
        "// combining class. Two different NFC strings are never canonically",
        "// equivalent, so no two folder names meet in one directory on macOS.",
        "// Sorted, non-overlapping, inclusive ranges.",
        "#pragma once",
        "",
        "namespace UltraMail {",
        "",
        "struct NfcEscapeRange { char32_t first, last; };",
        "",
        "inline constexpr const char* kNfcEscapeUnicodeVersion = \""
        + unicodedata.unidata_version + "\";",
        "",
        "inline constexpr NfcEscapeRange kNfcEscapeRanges[] = {",
    ]
    row = []
    for first, last in rs:
        row.append("{0x%05X, 0x%05X}," % (first, last))
        if len(row) == 4:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines += ["};", "", "} // namespace UltraMail", ""]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            import re
            m = re.search(r'kNfcEscapeUnicodeVersion = "([^"]+)"', current)
            made_from = m.group(1) if m else "?"
            if made_from != unicodedata.unidata_version:
                print(f"{OUT.relative_to(ROOT)} was made from Unicode {made_from}; "
                      f"this Python ({sys.version.split()[0]}) has Unicode "
                      f"{unicodedata.unidata_version}. Regenerate it with this Python "
                      f"(python3 scripts/{Path(__file__).name}) and pin the new Python "
                      f"version in .github/workflows/ultramail-nfc-table.yml.")
            else:
                print(f"{OUT.relative_to(ROOT)} does not match Unicode "
                      f"{unicodedata.unidata_version}: it was edited by hand or the "
                      f"script changed - run python3 scripts/{Path(__file__).name}")
            return 1
        print(f"{OUT.relative_to(ROOT)}: up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
