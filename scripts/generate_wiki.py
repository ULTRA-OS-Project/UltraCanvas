def build() -> dict[pathlib.Path, str]:
    reg = Registry()
    out: dict[pathlib.Path, str] = {}
    for c in reg.elements:
        out[WIKI / "Elements" / element_page_name(c)] = render_element(reg, c)
    for g in reg.groups:
        out[WIKI / "Groups" / f"{g.slug}.md"] = render_group(reg, g)
    out[WIKI / "Element-Index.md"] = render_element_index(reg)
    out[WIKI / "Callback-Index.md"] = render_callback_index(reg)
    out[WIKI / "_Sidebar.md"] = render_sidebar(reg)
    # the group list for Home.md, between markers
    home = WIKI / "Home.md"
    if home.exists():
        text = home.read_text()
        block = "\n".join(f"| [{g.title}](Groups/{g.slug}.md) | "
                          f"{sum(1 for x in reg.group_of.values() if x is g)} |" for g in reg.groups)
        block = "| Group | Elements |\n|---|---|\n" + block
        new = re.sub(r"(<!-- groups:begin -->\n).*?(\n<!-- groups:end -->)",
                     lambda m: m.group(1) + block + m.group(2), text, flags=re.S)
        new = re.sub(r"<!-- count:elements -->\d*<!-- /count -->",
                     f"<!-- count:elements -->{len([e for e in reg.elements if e not in FRAMEWORK_CLASSES])}<!-- /count -->", new)
        ncb = sum(len(callbacks_of(reg.members(c))) for c in reg.elements)
        new = re.sub(r"<!-- count:callbacks -->\d*<!-- /count -->",
                     f"<!-- count:callbacks -->{ncb}<!-- /count -->", new)
        out[home] = new
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when the generated pages are stale")
    args = ap.parse_args()
    pages = build()
    stale = []
    generated_dirs = [WIKI / "Elements", WIKI / "Groups"]
    existing = {p for d in generated_dirs if d.is_dir() for p in d.glob("*.md")}
    for path, text in pages.items():
        old = path.read_text() if path.exists() else None
        if old != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    orphans = existing - set(pages)
    for p in orphans:
        stale.append(p)
        if not args.check:
            p.unlink()
    if args.check:
        if stale:
            print(f"generate_wiki: {len(stale)} page(s) stale, e.g. {rel(stale[0])}; "
                  "run python3 scripts/generate_wiki.py")
            return 1
        print(f"generate_wiki: up to date ({len(pages)} pages).")
        return 0
    print(f"generate_wiki: {len(pages)} pages, {len(stale)} written or removed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
