# --------------------------------------------------------------------------
# A small C++ declaration scanner. It does not understand C++; it splits a
# header into top-level statements (with their leading comments), descends
# into namespaces, and hands back classes / structs / enums / free functions
# with their bodies. That is all the reference needs.
# --------------------------------------------------------------------------


@dataclass
class Stmt:
    text: str            # the statement without comments, whitespace folded
    doc: str             # leading // or /* */ comment, plus a trailing // one
    body: str | None     # the text between the braces of a block, if any
    line: int


def _strip_preprocessor(src: str) -> str:
    """Blank out preprocessor lines (keeping line numbers)."""
    out = []
    cont = False
    for line in src.split("\n"):
        stripped = line.lstrip()
        if cont or stripped.startswith("#"):
            cont = line.rstrip().endswith("\\")
            out.append("")
        else:
            out.append(line)
    return "\n".join(out)


def split_statements(src: str, base_line: int = 1) -> list[Stmt]:
    """Split `src` into statements at brace depth 0."""
    stmts: list[Stmt] = []
    i, n = 0, len(src)
    buf: list[str] = []
    comments: list[str] = []
    pending_doc: list[str] = []
    body: str | None = None
    line = base_line
    start_line = line

    def flush(trailing: str = "") -> None:
        nonlocal buf, comments, body, pending_doc, start_line
        text = " ".join("".join(buf).split())
        doc_parts = [c for c in pending_doc]
        if trailing:
            doc_parts.append(trailing)
        if text:
            stmts.append(Stmt(text, clean_doc(doc_parts), body, start_line))
        buf = []
        body = None
        pending_doc = []
        start_line = line

    while i < n:
        c = src[i]
        if c == "\n":
            line += 1
            buf.append(" ")
            i += 1
            continue
        if src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            comment = src[i + 2:j].strip()
            if "".join(buf).strip():
                # comment inside / after a statement: keep as part of doc
                pending_doc.append(comment)
            else:
                if is_banner(comment):
                    pending_doc = []          # a ruler / section banner ends a doc block
                else:
                    pending_doc.append(comment)
            i = j
            continue
        if src.startswith("/*", i):
            j = src.find("*/", i + 2)
            j = n if j < 0 else j
            comment = src[i + 2:j]
            line += comment.count("\n")
            text = " ".join(l.strip().lstrip("*").strip() for l in comment.split("\n"))
            # a /* name */ inside a statement is a parameter name, not a doc
            if not is_banner(text) and not "".join(buf).strip():
                pending_doc.append(text.strip())
            i = j + 2
            continue
        if c in "\"'":
            j = i + 1
            while j < n and src[j] != c:
                if src[j] == "\\":
                    j += 1
                j += 1
            buf.append(src[i:j + 1])
            i = j + 1
            continue
        if c == "R" and src.startswith('R"', i):
            m = re.match(r'R"([^(\s]*)\(', src[i:])
            if m:
                end = src.find(")" + m.group(1) + '"', i)
                end = n if end < 0 else end + len(m.group(1)) + 2
                line += src[i:end].count("\n")
                buf.append('R"..."')
                i = end
                continue
        if c == "{":
            # find matching brace
            depth, j = 0, i
            while j < n:
                ch = src[j]
                if ch == "{":
                    depth += 1
                elif ch == "}":
                    depth -= 1
                    if depth == 0:
                        break
                elif src.startswith("//", j):
                    k = src.find("\n", j)
                    j = n if k < 0 else k
                    continue
                elif src.startswith("/*", j):
                    k = src.find("*/", j + 2)
                    j = n if k < 0 else k + 2
                    continue
                elif ch in "\"'":
                    k = j + 1
                    while k < n and src[k] != ch:
                        if src[k] == "\\":
                            k += 1
                        k += 1
                    j = k
                j += 1
            inner = src[i + 1:j]
            body_line = line
            line += inner.count("\n")
            i = j + 1
            head = "".join(buf).strip()
            # look ahead: an initialiser `= {...};` or a type `struct X {...};`
            k = i
            while k < n and src[k] in " \t":
                k += 1
            nxt = src[k] if k < n else ""
            is_init = head.endswith("=") or re.search(r"[\w>\]]\s*$", head) and not re.search(
                r"\)\s*(const|override|final|noexcept|mutable|->\s*[\w:<>]+|\s)*$", head)
            if re.match(r"^(namespace|extern\s+\"C\")\b", head) or head.startswith("extern \"C\""):
                body = inner
                body_line_for = body_line
                text = " ".join(head.split())
                stmts.append(Stmt(text, clean_doc(pending_doc), inner, start_line))
                buf, pending_doc, body = [], [], None
                start_line = line
                continue
            if re.match(r"^(template\s*<.*>\s*)?(class|struct|union|enum)\b", head) or head.startswith("typedef struct"):
                body = inner
                buf.append(" {BODY}")
                continue
            is_func = bool(re.search(r"\)\s*(const|override|final|noexcept|mutable|&&|&|->\s*[\w:<>*&, ]+|\s)*$", head)) \
                and not head.endswith("=") and not re.search(r"=\s*\[[^\]]*\]\s*\([^)]*\)[^=]*$", head)
            if not is_func and (nxt in ";," or is_init):
                if nxt in ";,":
                    buf.append("{" + " ".join(inner.split()) + "}")
                    continue
            # a function body: the statement ends here
            body = inner
            # trailing comment on the same line
            trailing = ""
            m = re.match(r"[ \t]*//([^\n]*)", src[i:])
            if m:
                trailing = m.group(1).strip()
                i += m.end()
            flush(trailing)
            continue
        if c == "}":
            i += 1
            continue
        if c == ";":
            i += 1
            trailing = ""
            m = re.match(r"[ \t]*//([^\n]*)", src[i:])
            if m:
                trailing = m.group(1).strip()
                i += m.end()
            flush(trailing)
            continue
        if c == ":" and not src.startswith("::", i) and (i == 0 or src[i - 1] != ":"):
            head = "".join(buf).strip()
            if head in ("public", "protected", "private", "signals", "public slots"):
                stmts.append(Stmt(head + ":", "", None, line))
                buf = []
                pending_doc = []
                i += 1
                continue
        if not "".join(buf).strip():
            start_line = line
        buf.append(c)
        i += 1
    return stmts


def is_banner(comment: str) -> bool:
    """A ruler (`// ======`) or a section banner (`// ===== CALLBACKS =====`,
    `// FACTORY FUNCTIONS`): structure, not documentation."""
    c = comment.strip()
    if not c.strip("=-*/#~ "):
        return True
    if re.match(r"^[=\-*#~]{3,}.*[=\-*#~]{3,}$", c) or re.match(r"^[=\-*#~]{3,}", c):
        return True
    letters = re.sub(r"[^A-Za-z]", "", c)
    if bool(letters) and letters.isupper() and len(c.split()) <= 6:
        return True
    # a short heading such as "Callbacks", "Event callbacks", "Getters/setters"
    return len(c.split()) <= 4 and not re.search(r"[.,:;()]", c) and bool(re.search(
        r"(?i)\b(callbacks?|events?|methods|properties|getters?|setters?|accessors|overrides|"
        r"constructors?|destructors?|helpers|configuration|state|members|fields|data|api|"
        r"interface|public|private|protected|rendering|styling|utility|utilities)\b", c)) \
        and not re.search(r"(?i)\b(called|fires|when|if|while|after|before|returns?)\b", c)


def clean_doc(parts: list[str]) -> str:
    text = " ".join(p.strip() for p in parts if p.strip())
    text = re.sub(r"^[=\-\s]+|[=\-\s]+$", "", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


@dataclass
class Member:
    kind: str            # callback, method, field, ctor
    name: str
    signature: str
    doc: str
    access: str


@dataclass
class TypeDecl:
    kind: str            # class, struct, enum
    name: str
    bases: list[str]
    body: str
    doc: str
    header: pathlib.Path
    line: int
    nested_in: str = ""


@dataclass
class HeaderInfo:
    path: pathlib.Path
    types: dict[str, TypeDecl] = field(default_factory=dict)
    functions: list[Stmt] = field(default_factory=list)


_HEADER_CACHE: dict[pathlib.Path, HeaderInfo] = {}


def parse_header(path: pathlib.Path) -> HeaderInfo:
    if path in _HEADER_CACHE:
        return _HEADER_CACHE[path]
    info = HeaderInfo(path)
    src = _strip_preprocessor(path.read_text(errors="replace"))

    def walk(text: str, base_line: int, outer: str) -> None:
        for st in split_statements(text, base_line):
            if st.body is not None and re.match(r"^(namespace|extern)\b", st.text):
                walk(st.body, st.line, outer)
                continue
            decl = type_from_stmt(st, path, outer)
            if decl:
                info.types.setdefault(decl.name, decl)
                if decl.kind in ("class", "struct"):
                    walk_nested(decl)
                continue
            if st.body is not None or "(" in st.text:
                if re.match(r"^(using|typedef|friend|static_assert)\b", st.text):
                    continue
                info.functions.append(st)

    def walk_nested(decl: TypeDecl) -> None:
        for st in split_statements(decl.body, decl.line):
            sub = type_from_stmt(st, path, decl.name)
            if sub and sub.name not in info.types:
                info.types[sub.name] = sub

    walk(src, 1, "")
    _HEADER_CACHE[path] = info
    return info


TYPE_RE = re.compile(
    r"^(?:template\s*<[^{]*>\s*)?(class|struct|union|enum\s+class|enum\s+struct|enum)\s+"
    r"(?:\[\[[^\]]*\]\]\s*)?(?:[A-Z_]+_EXPORT\s+)?([A-Za-z_]\w*)\s*(?:final\s*)?"
    r"(?::\s*([^{]*?))?\s*\{BODY\}")


def type_from_stmt(st: Stmt, path: pathlib.Path, outer: str) -> TypeDecl | None:
    if st.body is None:
        return None
    m = TYPE_RE.match(st.text)
    if not m:
        return None
    kind = m.group(1).split()[0]
    if kind == "union":
        kind = "struct"
    name = m.group(2)
    bases = []
    if m.group(3) and kind != "enum":
        for b in m.group(3).split(","):
            b = re.sub(r"\b(public|protected|private|virtual)\b", "", b).strip()
            b = b.split("::")[-1] if "<" not in b else b
            if b:
                bases.append(b)
    return TypeDecl(kind, name, bases, st.body, st.doc, path, st.line, outer)


def top_level_paren(text: str) -> int:
    """Index of the first '(' outside template brackets, -1 if none."""
    depth = 0
    for idx, ch in enumerate(text):
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth = max(0, depth - 1)
        elif ch == "(" and depth == 0:
            return idx
        elif ch == "=" and depth == 0:
            return -1
    return -1


def class_members(decl: TypeDecl) -> list[Member]:
    access = "public" if decl.kind == "struct" else "private"
    out: list[Member] = []
    for st in split_statements(decl.body, decl.line):
        t = st.text
        if t in ("public:", "protected:", "private:", "signals:", "public slots:"):
            access = t[:-1].split()[0]
            continue
        if TYPE_RE.match(t):
            continue
        if re.match(r"^(using|typedef|friend|static_assert|template\s*<[^>]*>\s*friend)\b", t):
            continue
        t = re.sub(r"\[\[[^\]]*\]\]\s*", "", t)
        t = re.sub(r"\s*\{BODY\}", "", t)
        t = t.replace("{ ", "{").replace(" }", "}")
        if not t or t.startswith("~") and access != "public":
            continue
        if re.match(r"^(Q_OBJECT|UC_[A-Z_]+|ULTRACANVAS_[A-Z_]+)\b[^(]*$", t):
            continue
        if re.search(r"\boperator\b", t):
            continue                      # operators are not part of an element's API story
        p = top_level_paren(t)
        if p >= 0:
            head = t[:p].rstrip()
            mname = re.search(r"(operator\s*\S+|~?[A-Za-z_]\w*)$", head)
            if not mname:
                continue
            name = mname.group(1)
            sig = t
            # drop inline initialiser lists of constructors
            sig = re.sub(r"\)\s*:\s*[A-Za-z_].*$", ")", sig) if name in (decl.name, "~" + decl.name) else sig
            sig = re.sub(r"\s*=\s*(default|delete|0)\s*$", lambda m: " = " + m.group(1), sig)
            if name == decl.name or name == "~" + decl.name:
                kind = "ctor"
            elif "std::function<" in sig[sig.find("("):]:
                kind = "callback-setter"
            else:
                kind = "method"
            out.append(Member(kind, name, sig, st.doc, access))
            continue
        # a field (maybe several: `int a = 0, b = 1;`)
        m = re.match(r"^(?:static\s+|inline\s+|mutable\s+|constexpr\s+|const\s+)*(.+?)\s+&?\*?([A-Za-z_]\w*)\s*(\[[^\]]*\])?\s*(=.*|\{.*\})?$", t)
        if not m:
            continue
        type_ = m.group(1)
        name = m.group(2)
        kind = "callback" if re.match(r"^(std::)?function<", type_) or re.search(r"Callback\b|Handler\b", type_) and "std::" not in type_[:4] else "field"
        if kind == "callback" and not (type_.startswith("std::function") or type_.startswith("function")):
            # a typedef'd callback type, e.g. `ClickCallback onClick`
            kind = "callback" if name.startswith("on") or name.endswith("Callback") else "field"
        out.append(Member(kind, name, t, st.doc, access))
    return out


def enum_values(decl: TypeDecl) -> list[tuple[str, str]]:
    """The values of an enum with their comments: a comment on a value's
    own line describes it; comment lines above a value describe the next one."""
    vals: list[list[str]] = []   # [name, doc]
    leading: list[str] = []
    in_block = False
    for raw in decl.body.split("\n"):
        if in_block:
            if "*/" in raw:
                in_block = False
            continue
        code_part, _, comment = raw.partition("//")
        if "/*" in code_part and "*/" not in code_part:
            in_block = True
            code_part = code_part.split("/*")[0]
        block_doc = " ".join(re.findall(r"/\*+(.*?)\*/", code_part))
        code_part = re.sub(r"/\*.*?\*/", "", code_part)
        comment = (comment.strip() + " " + block_doc.strip()).strip()
        names = []
        for part in code_part.split(","):
            part = " ".join(part.split())
            if not part or part.startswith("#"):
                continue
            m = re.match(r"^([A-Za-z_]\w*)\s*(?:=\s*(.+))?$", part)
            if m:
                names.append(m.group(1) + (" = " + m.group(2) if m.group(2) else ""))
        if not names:
            if comment and not is_banner(comment):
                leading.append(comment)
            elif not comment:
                leading = []
            continue
        for k, nm in enumerate(names):
            doc = list(leading) if k == 0 else []
            if k == len(names) - 1 and comment:
                doc.append(comment)
            vals.append([nm, clean_doc(doc)])
        leading = []
    return [(v[0], v[1]) for v in vals]


