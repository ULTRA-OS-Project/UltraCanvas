@dataclass
class Group:
    title: str
    slug: str
    intro: str
    rows: list[tuple[str, list[str], str]] = field(default_factory=list)  # need, classes, header-cell


def slugify(title: str) -> str:
    title = re.sub(r"`[^`]*`", "", title)
    title = title.replace("—", "-").replace("–", "-")
    s = re.sub(r"[^A-Za-z0-9]+", "-", title).strip("-")
    return s


def fix_links(text: str, depth: str) -> str:
    """Rewrite the catalogue's relative doc links for a page under Docs/Wiki/<sub>/."""
    def repl(m: re.Match) -> str:
        target = m.group(2)
        if re.match(r"^(https?:|#|/)", target):
            return m.group(0)
        return f"[{m.group(1)}]({depth}../UltraCanvas/{target})"
    return re.sub(r"\[([^\]]+)\]\(([^)]+)\)", repl, text)


def parse_catalogue() -> list[Group]:
    groups: list[Group] = []
    cur: Group | None = None
    parent = ""
    stop = {"Creating them", "The two legitimate exceptions", "Enforcement",
            "When the element does not exist"}
    intro_lines: list[str] = []
    for line in CATALOGUE.read_text().split("\n"):
        m = re.match(r"^(##+)\s+(.*)$", line)
        if m:
            level, title = len(m.group(1)), m.group(2).strip()
            if level == 2:
                parent = title
            if title in stop:
                cur = None
                continue
            if level == 2 and title.startswith("Charts, diagrams and codes"):
                cur = Group("Plugin elements - overview", "Plugin-Elements", "")
                groups.append(cur)
                continue
            clean = re.sub(r"\s*[—-]\s*`[^`]*`\s*$", "", title).strip()
            cur = Group(clean, slugify(clean), "")
            groups.append(cur)
            continue
        if cur is None:
            continue
        if line.startswith("|"):
            cells = [c.strip() for c in split_row(line)]
            if len(cells) < 2 or set(cells[0]) <= set("-: ") or cells[0] in ("You need", "Widget"):
                continue
            classes = re.findall(r"`((?:UltraCanvas|SmartHome)[A-Za-z0-9_]*)", cells[1])
            header = cells[-1]
            cur.rows.append((cells[0], classes, header))
        else:
            cur.intro += line + "\n"
    return [g for g in groups if g.rows or g.intro.strip()]


def split_row(line: str) -> list[str]:
    cells, cur, tick = [], "", False
    for ch in line.strip().strip("|"):
        if ch == "`":
            tick = not tick
        if ch == "|" and not tick:
            cells.append(cur)
            cur = ""
        else:
            cur += ch
    cells.append(cur)
    return cells


