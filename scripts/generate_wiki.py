def find_elements() -> dict[str, pathlib.Path]:
    found: dict[str, pathlib.Path] = dict(ROOT_CLASSES)
    for d in SEARCH_DIRS:
        if not d.is_dir():
            continue
        for header in sorted(d.rglob("*.h")):
            text = header.read_text(errors="replace")
            for name, _base in ELEMENT_BASE.findall(text):
                found.setdefault(name, header)
    # SmartHome widgets live in the SmartHome module
    sh = ROOT / "SmartHome"
    if sh.is_dir():
        for header in sorted(sh.rglob("*.h")):
            text = header.read_text(errors="replace")
            for name in re.findall(r"\bclass\s+(SmartHome[A-Za-z0-9_]+)\s*(?:final\s*)?:\s*public\s+(?:UltraCanvas::)?UltraCanvas\w+", text):
                found.setdefault(name, header)
    return found


def rel(path: pathlib.Path) -> str:
    return path.relative_to(ROOT).as_posix()


def short_name(cls: str) -> str:
    s = cls[len("UltraCanvas"):] if cls.startswith("UltraCanvas") and len(cls) > 11 else cls
    return s or cls


def md_escape(text: str) -> str:
    return text.replace("|", "\\|")


def code(text: str) -> str:
    text = text.replace("|", "\\|")
    if "`" in text:
        return "``" + text + "``"
    return "`" + text + "`"


def doc_cell(text: str, limit: int = 320, header_text: bool = True) -> str:
    text = text.strip()
    if header_text:
        # a header comment is not Markdown: `[text](url)` in it is an example
        parts = text.split("`")
        text = "`".join(part if k % 2 else part.replace("[", "\\[").replace("]", "\\]")
                        for k, part in enumerate(parts))
    if len(text) > limit:
        cut = text[:limit].rsplit(" ", 1)[0]
        text = cut + " …"
    # keep code-ish bits readable inside a table cell
    return md_escape(text).replace("<", "&lt;").replace(">", "&gt;") if "`" not in text else md_escape(text)


def find_component_docs(cls: str) -> list[pathlib.Path]:
    hits = []
    pat = re.compile(r"\b%s\b" % re.escape(cls))
    sn = short_name(cls)
    for p in sorted(COMPONENT_DOCS.glob("*.md")):
        if p.name in ("CHANGELOG.md", "UltraCanvasUIElements.md"):
            continue
        txt = _doc_text(p)
        if pat.search(txt):
            score = 0
            stem = p.stem.replace("UltraCanvas", "")
            if stem == sn or stem in (sn + "Examples", sn + "Element"):
                score = 3
            elif stem.startswith(sn) or sn.startswith(stem):
                score = 2
            elif re.search(r"Proposal|Plan|Investigation|DesignVariants", p.stem):
                score = -1
            hits.append((score, -len(pat.findall(txt)), p))
    hits.sort(key=lambda h: (-h[0], h[1], h[2].name))
    return [h[2] for h in hits[:6]]


_DOC_CACHE: dict[pathlib.Path, str] = {}


def _doc_text(p: pathlib.Path) -> str:
    if p not in _DOC_CACHE:
        _DOC_CACHE[p] = p.read_text(errors="replace")
    return _DOC_CACHE[p]


class Registry:
    def __init__(self) -> None:
        self.elements = find_elements()
        for name, (header, _purpose) in FRAMEWORK_CLASSES.items():
            if header.exists():
                self.elements[name] = header
        self.decls: dict[str, TypeDecl] = {}
        for name, header in self.elements.items():
            info = parse_header(header)
            if name in info.types:
                self.decls[name] = info.types[name]
        self.groups = parse_catalogue()
        self.group_of: dict[str, Group] = {}
        self.purpose: dict[str, str] = {}
        fw = Group(FRAMEWORK_GROUP[0], FRAMEWORK_GROUP[1], FRAMEWORK_GROUP[2])
        for name, (_h, purpose) in FRAMEWORK_CLASSES.items():
            if name in self.elements:
                fw.rows.append((purpose, [name], ""))
                self.group_of[name] = fw
                self.purpose[name] = purpose
        self.groups.insert(0, fw)
        for g in self.groups:
            for need, classes, _hdr in g.rows:
                for c in classes:
                    self.group_of.setdefault(c, g)
                    self.purpose.setdefault(c, need)
        cat = CATALOGUE.read_text()
        # an element named only in prose: put it in the section that names it
        for name in self.elements:
            if name in self.group_of:
                continue
            sec = None
            for line in cat.split("\n"):
                m = re.match(r"^##+\s+(.*)$", line)
                if m:
                    clean = re.sub(r"\s*[—-]\s*`[^`]*`\s*$", "", m.group(1)).strip()
                    sec = next((g for g in self.groups if g.title == clean), None)
                elif sec and re.search(r"\b%s\b" % re.escape(name), line):
                    self.group_of[name] = sec
                    break
        self.other = Group("Base classes and other elements", "Base-And-Other-Elements",
                           "The two classes every element derives from, and the elements the "
                           "catalogue names outside its tables or not at all (shared bases, "
                           "elements behind a catalogued facade).\n")
        self.groups.append(self.other)
        for name in sorted(self.elements):
            if name not in self.group_of:
                self.group_of[name] = self.other
                self.other.rows.append(("", [name], ""))

    def base_chain(self, name: str) -> list[str]:
        chain, seen = [], {name}
        cur = name
        while True:
            d = self.decls.get(cur)
            if not d or not d.bases:
                break
            nxt = None
            for b in d.bases:
                b = re.sub(r"<.*", "", b).split("::")[-1]
                if b in self.decls or b in self.elements:
                    nxt = b
                    break
            if nxt is None:
                chain.append(re.sub(r"<.*", "", d.bases[0]).split("::")[-1])
                break
            if nxt in seen:
                break
            chain.append(nxt)
            seen.add(nxt)
            cur = nxt
        return chain

    def members(self, name: str) -> list[Member]:
        d = self.decls.get(name)
        return class_members(d) if d else []


