def element_page_name(cls: str) -> str:
    return f"{cls}.md"


def element_link(reg: Registry, cls: str, from_dir: str) -> str:
    if cls in reg.elements:
        prefix = "" if from_dir == "Elements" else ("../Elements/" if from_dir == "Groups" else "Elements/")
        return f"[`{cls}`]({prefix}{element_page_name(cls)})"
    return f"`{cls}`"


def callbacks_of(members: list[Member]) -> list[Member]:
    return [m for m in members if m.access == "public" and m.kind in ("callback", "callback-setter")]


def humanize(name: str) -> str:
    """`onItemDoubleClicked` -> '_Item double clicked_' for a callback the header leaves undocumented."""
    n = re.sub(r"^on", "", name)
    words = re.findall(r"[A-Z]?[a-z0-9]+|[A-Z]+(?![a-z])", n)
    if not words:
        return "-"
    text = " ".join(w.lower() for w in words)
    return "_" + text[0].upper() + text[1:] + "_"


def callback_params(sig: str) -> str:
    m = re.search(r"function<(.*)>", sig)
    return m.group(1) if m else ""


def render_element(reg: Registry, cls: str) -> str:
    header = reg.elements[cls]
    decl = reg.decls.get(cls)
    group = reg.group_of[cls]
    members = reg.members(cls)
    pub = [m for m in members if m.access == "public"]
    prot = [m for m in members if m.access == "protected" and m.kind != "ctor"]
    include = rel(header)
    for d in ("UltraCanvas/include/", "UltraCanvas/Plugins/", "UltraCanvas/dialogs/"):
        if include.startswith(d):
            include = include[len(d):]
    lines = [GENERATED_BANNER, "", f"# {short_name(cls)}", ""]
    lines.append(f"**Class:** `{cls}` · **Group:** [{group.title}](../Groups/{group.slug}.md) · "
                 f"**Header:** [`{rel(header)}`](../../../{rel(header)}) · `#include \"{include}\"`")
    lines.append("")
    chain = reg.base_chain(cls)
    if chain:
        parts = [element_link(reg, c, "Elements") for c in chain]
        lines.append("**Inherits:** " + " → ".join(parts))
        lines.append("")
    derived = sorted(n for n, d in reg.decls.items()
                     if any(re.sub(r"<.*", "", b).split("::")[-1] == cls for b in d.bases))
    if derived:
        lines.append("**Derived elements:** " + ", ".join(element_link(reg, d, "Elements") for d in derived))
        lines.append("")
    purpose = reg.purpose.get(cls)
    if purpose:
        lines += ["## What it is for", "", fix_links(purpose, "../"), ""]
    if decl and decl.doc:
        lines += ["## Overview", "", decl.doc, ""]
    docs = find_component_docs(cls)
    if docs:
        lines += ["## Guides and examples", "",
                  "The component documentation with explained, compiled C++ examples:", ""]
        for p in docs:
            lines.append(f"- [{p.stem}](../../UltraCanvas/{p.name})")
        lines.append("")

    # factories
    info = parse_header(header)
    factories = []
    for st in info.functions:
        t = re.sub(r"\s*\{BODY\}", "", st.text)
        if re.search(r"\b(Create\w*|Make\w*)\s*\(", t) and (short_name(cls) in t or cls in t):
            sig = re.sub(r"^(inline|static)\s+", "", t)
            factories.append((sig, st.doc))
    ctors = [m for m in pub if m.kind == "ctor" and not m.name.startswith("~")]
    if factories or ctors:
        lines += ["## Creating it", ""]
        if factories:
            lines += ["Factory functions (the usual way - every element is held in a `std::shared_ptr`):", ""]
            lines += ["```cpp"] + [f + ";" + (f"   // {d}" if d and len(d) < 100 else "") for f, d in factories] + ["```", ""]
        if ctors:
            lines += ["Constructors:", "", "```cpp"]
            lines += [c.signature + ";" for c in ctors]
            lines += ["```", ""]
        lines.append("The first string argument is always the element's **identifier**, never its text "
                     "(see [Core concepts](../Core-Concepts.md#identifiers)).")
        lines.append("")

    cbs = callbacks_of(members)
    lines += ["## Callbacks", ""]
    if cbs:
        lines += ["Assign a lambda to the member (or call the setter). Capture the element and its "
                  "parents **raw**, never as a `shared_ptr` - see "
                  "[Events and callbacks](../Events-and-Callbacks.md#ownership).", "",
                  "| Callback | Signature | When it fires |", "|---|---|---|"]
        for m in cbs:
            if m.kind == "callback":
                sig = re.sub(r"\s*(=.*|\{.*\})$", "", m.signature)
                lines.append(f"| `{m.name}` | {code(sig)} | {doc_cell(m.doc) or humanize(m.name)} |")
            else:
                lines.append(f"| `{m.name}()` | {code(m.signature)} | {doc_cell(m.doc) or 'Takes a callback.'} |")
        lines.append("")
    else:
        lines += ["This class declares no callbacks of its own.", ""]
    inherited = []
    for base in chain:
        bcbs = callbacks_of(reg.members(base))
        if bcbs:
            inherited.append((base, bcbs))
    if inherited:
        lines += ["**Inherited callbacks:**", ""]
        for base, bcbs in inherited:
            names = ", ".join(f"`{m.name}`" for m in bcbs)
            lines.append(f"- from {element_link(reg, base, 'Elements')}: {names}")
        lines.append("")

    # options: setters / getters / methods / fields
    setters = [m for m in pub if m.kind == "method" and re.match(r"^(Set|Enable|Disable|Show|Hide|Add|Remove|Clear|Insert)", m.name)]
    getters = [m for m in pub if m.kind == "method" and re.match(r"^(Get|Is|Has|Can|Count|Find)", m.name)]
    others = [m for m in pub if m.kind == "method" and m not in setters and m not in getters]
    fields = [m for m in pub if m.kind == "field"]

    def table(title: str, items: list[Member], intro: str = "") -> None:
        if not items:
            return
        lines.extend([f"## {title}", ""])
        if intro:
            lines.extend([intro, ""])
        lines.extend(["| Member | Signature | Notes |", "|---|---|---|"])
        seen = set()
        for m in items:
            key = m.signature
            if key in seen:
                continue
            seen.add(key)
            lines.append(f"| `{m.name}` | {code(m.signature)} | {doc_cell(m.doc)} |")
        lines.append("")

    table("Options and setters", setters,
          "Everything that configures the element: appearance, behaviour and content.")
    table("Queries", getters)
    table("Other methods", others)
    table("Public fields", fields,
          "Fields set directly (often the element's style or state struct).")
    if prot:
        virt = [m for m in prot if m.kind == "method" and ("virtual" in m.signature or "override" in m.signature)]
        if virt:
            table("Overridable (protected)", virt, "Hooks for a class that derives from this one.")

    # option structs and enums in the same header
    types = [t for t in info.types.values() if t.name != cls and t.kind in ("struct", "enum")
             and (not t.nested_in or t.nested_in == cls)]
    if types:
        lines += ["## Option types in this header", ""]
        for t in types:
            lines += [f"### {t.kind} `{t.name}`", ""]
            if t.doc:
                lines += [t.doc, ""]
            if t.kind == "enum":
                vals = enum_values(t)
                if vals:
                    lines += ["| Value | Meaning |", "|---|---|"]
                    lines += [f"| `{md_escape(v)}` | {doc_cell(d)} |" for v, d in vals]
                    lines.append("")
            else:
                ms = [m for m in class_members(t) if m.access == "public"]
                flds = [m for m in ms if m.kind in ("field", "callback")]
                meths = [m for m in ms if m.kind in ("method", "callback-setter")]
                if flds:
                    lines += ["| Field | Declaration | Notes |", "|---|---|---|"]
                    lines += [f"| `{m.name}` | {code(m.signature)} | {doc_cell(m.doc)} |" for m in flds]
                    lines.append("")
                if meths:
                    lines.append("Methods: " + ", ".join(f"`{m.name}`" for m in {x.name: x for x in meths}.values()))
                    lines.append("")
    lines += ["---", "", f"[← {group.title}](../Groups/{group.slug}.md) · [All elements](../Element-Index.md) · "
              "[Callback index](../Callback-Index.md) · [Home](../Home.md)", ""]
    return "\n".join(lines)


def render_group(reg: Registry, g: Group) -> str:
    lines = [GENERATED_BANNER, "", f"# {g.title}", ""]
    intro = g.intro.strip()
    if intro:
        lines += [fix_links(intro, "../"), ""]
    if g.slug == "Plugin-Elements":
        subs = [x for x in reg.groups if x.title.startswith(("Charts", "Diagrams", "Codes"))]
        lines += ["The plugin families:", ""]
        lines += [f"- [{s.title}]({s.slug}.md)" for s in subs]
        lines.append("")
    members = sorted({c for c, gg in reg.group_of.items() if gg is g})
    if members:
        lines += ["## Elements", "", "| Element | What it is for | Callbacks |", "|---|---|---|"]
        for c in members:
            cbs = callbacks_of(reg.members(c))
            names = ", ".join(f"`{m.name}`" for m in cbs[:8]) + (" …" if len(cbs) > 8 else "")
            inh = sum(len(callbacks_of(reg.members(b))) for b in reg.base_chain(c))
            if inh:
                names = (names + " " if names else "") + f"(+{inh} inherited)"
            need = doc_cell(re.sub(r"\(\[doc\]\([^)]*\)\)", "", reg.purpose.get(c, "")), 220, header_text=False)
            lines.append(f"| {element_link(reg, c, 'Groups')} | {need} | {names or '-'} |")
        lines.append("")
    # rows naming classes that are not element classes (models, helpers)
    extra = []
    for need, classes, hdr in g.rows:
        for c in classes:
            if c not in reg.elements:
                extra.append((c, need, hdr))
    if extra:
        lines += ["## Related types named in this group", "",
                  "Not elements themselves (models, helpers, dialogs built from elements), but part of the same feature:", "",
                  "| Type | Used for | Header |", "|---|---|---|"]
        seen = set()
        for c, need, hdr in extra:
            if c in seen:
                continue
            seen.add(c)
            lines.append(f"| `{c}` | {doc_cell(re.sub(r'\(\[doc\]\([^)]*\)\)', '', need), 200, header_text=False)} | {md_escape(hdr)} |")
        lines.append("")
    lines += ["---", "", "[Home](../Home.md) · [All elements](../Element-Index.md) · [Callback index](../Callback-Index.md)", ""]
    return "\n".join(lines)


def render_element_index(reg: Registry) -> str:
    lines = [GENERATED_BANNER, "", "# Element index", "",
             f"All {len(reg.elements)} element classes, A-Z, with their group and header.", "",
             "| Element | Group | Header | Callbacks |", "|---|---|---|---|"]
    for c in sorted(reg.elements, key=str.lower):
        g = reg.group_of[c]
        n = len(callbacks_of(reg.members(c)))
        inh = sum(len(callbacks_of(reg.members(b))) for b in reg.base_chain(c))
        lines.append(f"| {element_link(reg, c, '')} | [{g.title}](Groups/{g.slug}.md) | `{rel(reg.elements[c])}` | {n} own, {inh} inherited |")
    lines.append("")
    return "\n".join(lines)


def render_callback_index(reg: Registry) -> str:
    rows = []
    for c in reg.elements:
        for m in callbacks_of(reg.members(c)):
            sig = re.sub(r"\s*(=.*|\{.*\})$", "", m.signature) if m.kind == "callback" else m.signature
            rows.append((m.name, c, sig))
    rows.sort(key=lambda r: (r[0].lower(), r[1]))
    lines = [GENERATED_BANNER, "", "# Callback index", "",
             f"Every callback of every element - {len(rows)} in all - A-Z by name. "
             "A callback is a public `std::function` member (assign a lambda) or a method that "
             "takes one. Callbacks a class inherits are listed under the class that declares them; "
             "[`UltraCanvasUIElement`](Elements/UltraCanvasUIElement.md)'s apply to every element.", "",
             "| Callback | Element | Signature |", "|---|---|---|"]
    for name, c, sig in rows:
        lines.append(f"| `{name}` | {element_link(reg, c, '')} | {code(sig)} |")
    lines.append("")
    return "\n".join(lines)


