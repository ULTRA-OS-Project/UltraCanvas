std::string      UltraCrypt_GetBackendName();   // e.g. "libsodium 1.0.18"

// ============================================================================
// UltraCryptSecureBuffer — the type secrets travel in
// ============================================================================
// Move-only so a secret is never copied by accident, and zeroized on
// destruction so it does not linger in freed heap pages.
class UltraCryptSecureBuffer {
public:
    UltraCryptSecureBuffer() = default;
    explicit UltraCryptSecureBuffer(size_t size);            // zero-filled
    UltraCryptSecureBuffer(const void* data, size_t size);
    ~UltraCryptSecureBuffer();

    UltraCryptSecureBuffer(UltraCryptSecureBuffer&& other) noexcept;
    UltraCryptSecureBuffer& operator=(UltraCryptSecureBuffer&& other) noexcept;
    UltraCryptSecureBuffer(const UltraCryptSecureBuffer&) = delete;
    UltraCryptSecureBuffer& operator=(const UltraCryptSecureBuffer&) = delete;

    // Copying a secret must be deliberate.
    UltraCryptSecureBuffer Clone() const;

    uint8_t*       Data()       { return data_; }
    const uint8_t* Data() const { return data_; }
    size_t         GetSize() const { return size_; }
    bool           IsEmpty() const { return size_ == 0; }

    void Resize(size_t size);   // wipes any discarded bytes
    void Clear();               // zeroize and release

    // Best-effort mlock()/VirtualLock(): keeps pages out of swap. Returns false
    // when the OS refuses (e.g. RLIMIT_MEMLOCK) — a hint, never a guarantee.
    bool LockPages();

    // Adopts the bytes of a std::string and wipes the source in place, for
    // bridging from UI text fields that cannot hand over a secure buffer.
    static UltraCryptSecureBuffer AdoptString(std::string& text);

private:
    void Release();

    uint8_t* data_   = nullptr;
    size_t   size_   = 0;
    bool     locked_ = false;
};

