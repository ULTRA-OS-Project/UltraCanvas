void UltraCrypt_SecureZero(void* data, size_t size);

// Length-independent comparison. Use for every MAC / tag / digest check.
// Returns false when sizes differ.
bool UltraCrypt_ConstantTimeEquals(const void* a, size_t aSize,
                                   const void* b, size_t bSize);

// ============================================================================
// Hashing
// ============================================================================
enum class UltraCryptHashAlgorithm : uint8_t {
    // LEGACY. Provided for HMAC-SHA-1 only, which TOTP requires for issuer
    // compatibility and where SHA-1's collision weakness does not apply. As a
    // plain digest it is collision-broken: UltraCrypt_Hash refuses it unless
    // UltraCryptHashOptions::allowLegacy is set. One reader sets it, for
    // interop: UltraCanvasOfficeEncryption, to read the Office 2010 files
    // whose password key is SHA-1 - a key derivation, which collisions do not
    // reach. Nothing UltraCanvas writes uses it.
    SHA1,
    SHA256,
    SHA512
};

struct UltraCryptHashOptions {
    bool allowLegacy = false;    // required to use SHA1 as a plain digest
};

size_t UltraCrypt_GetDigestSize(UltraCryptHashAlgorithm algorithm);
bool   UltraCrypt_IsHashAvailable(UltraCryptHashAlgorithm algorithm);

UltraCryptResult UltraCrypt_Hash(UltraCryptHashAlgorithm algorithm,
                                 const void* data, size_t size,
                                 std::vector<uint8_t>& outDigest,
                                 const UltraCryptHashOptions& options =
                                     UltraCryptHashOptions());

UltraCryptResult UltraCrypt_HashFile(UltraCryptHashAlgorithm algorithm,
                                     const std::string& filePath,
                                     std::vector<uint8_t>& outDigest);

std::string UltraCrypt_ToHex(const std::vector<uint8_t>& bytes);
bool        UltraCrypt_FromHex(const std::string& hex,
                               std::vector<uint8_t>& outBytes);

// Streaming hash, for files and large payloads.
class UltraCryptHasher {
public:
    explicit UltraCryptHasher(UltraCryptHashAlgorithm algorithm);
    ~UltraCryptHasher();
    UltraCryptHasher(const UltraCryptHasher&) = delete;
    UltraCryptHasher& operator=(const UltraCryptHasher&) = delete;

    void Update(const void* data, size_t size);
    // Finalises and returns the digest; Reset() to reuse.
    std::vector<uint8_t> Final();
    void Reset();

    size_t GetDigestSize() const;
    bool   IsValid() const { return state_ != nullptr; }

private:
    UltraCryptHashAlgorithm algorithm_;
    void* state_ = nullptr;
};

