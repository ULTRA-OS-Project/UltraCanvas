// ============================================================================
// Authenticated encryption (AEAD)
// ============================================================================
enum class UltraCryptAeadAlgorithm : uint8_t {
    // The default, and the only cipher UltraCanvas ever writes. 192-bit nonce,
    // so randomly generated nonces are safe without bookkeeping; constant-time
    // in portable software on hardware without AES acceleration.
    XChaCha20Poly1305,

    // Interop only — for reading data produced elsewhere. Hardware-gated:
    // UltraCrypt_IsAeadAvailable returns false without AES-NI. Never select
    // this for new output.
    Aes256Gcm
};

struct UltraCryptAeadParams {
    UltraCryptAeadAlgorithm algorithm =
        UltraCryptAeadAlgorithm::XChaCha20Poly1305;

    // Seal: if empty, a fresh random nonce is generated and written back here
    // — the caller must store it. Supplying a nonce is allowed, but then
    // keeping it unique per key is the caller's responsibility.
    // Open: must be the nonce used at Seal time.
    std::vector<uint8_t> nonce;

    // Authenticated but not encrypted. Put file/section headers here so that
    // editing them invalidates the tag.
    std::vector<uint8_t> associatedData;
};

size_t UltraCrypt_GetKeySize(UltraCryptAeadAlgorithm algorithm);    // 32 both
size_t UltraCrypt_GetNonceSize(UltraCryptAeadAlgorithm algorithm);  // 24 / 12
size_t UltraCrypt_GetTagSize(UltraCryptAeadAlgorithm algorithm);    // 16
bool   UltraCrypt_IsAeadAvailable(UltraCryptAeadAlgorithm algorithm);

// Ciphertext is plaintext-length + tag size; the tag is appended.
UltraCryptResult UltraCrypt_AeadSeal(const UltraCryptSecureBuffer& key,
                                     UltraCryptAeadParams& params,
                                     const void* plaintext, size_t size,
                                     std::vector<uint8_t>& outCiphertext);

// Returns AuthenticationFailed — and leaves outPlaintext empty — if the
// ciphertext, the AAD or the nonce was altered. Never returns partially
// verified plaintext.
UltraCryptResult UltraCrypt_AeadOpen(const UltraCryptSecureBuffer& key,
                                     const UltraCryptAeadParams& params,
                                     const void* ciphertext, size_t size,
                                     UltraCryptSecureBuffer& outPlaintext);

// ============================================================================
// AES-CBC (interop only)
// ============================================================================
// AES (FIPS 197) in CBC mode (NIST SP 800-38A) with a 128-, 192- or 256-bit
// key, for formats defined elsewhere that are built on it - encrypted Office
// files, PDF's AESV2/AESV3, and the like. Never select it for anything
// UltraCanvas defines itself: CBC has no integrity, so a changed ciphertext
// decrypts to changed plaintext without a word, and that is what the AEAD
// functions above exist to prevent.
//
// Portable software, constant-time (bitsliced, no secret-indexed tables), and
// independent of libsodium - libsodium has no AES block cipher - so it runs on
// every CPU, with or without AES instructions.
//
// The rule that keeps CBC safe: when the format carries a MAC over the
// ciphertext (Office's dataIntegrity HMAC, an encrypt-then-MAC tag), check it
// with UltraCrypt_Hmac and UltraCrypt_ConstantTimeEquals BEFORE decrypting,
// and decrypt nothing that fails. A decrypter that answers "bad padding" to
// an attacker's chosen ciphertexts is a padding oracle, which recovers the
// plaintext without the key.
enum class UltraCryptCbcPadding : uint8_t {
    Pkcs7,   // PKCS #7 / RFC 5652: 1-16 bytes, each the pad length
    NoPadding // the plaintext is a whole number of blocks (the format pads)
              // (not `None`: X11 #defines None, see the note at the top)
};

struct UltraCryptCbcParams {
    // Encrypt: if empty, a fresh random IV is generated and written back here
    // - the caller must store it. A supplied IV must be unpredictable (random,
    // or derived as the format specifies); never a counter or a constant.
    // Decrypt: must be the IV used at encryption.
    std::vector<uint8_t> iv;

    UltraCryptCbcPadding padding = UltraCryptCbcPadding::Pkcs7;
};

size_t UltraCrypt_GetAesBlockSize();   // 16; also the IV size

// Ciphertext is the plaintext rounded up to whole blocks: with Pkcs7 always
// 1-16 bytes longer, with NoPadding the same length (and the plaintext must be a
// multiple of 16 bytes, else InvalidArgument).
UltraCryptResult UltraCrypt_AesCbcEncrypt(const UltraCryptSecureBuffer& key,
                                          UltraCryptCbcParams& params,
                                          const void* plaintext, size_t size,
                                          std::vector<uint8_t>& outCiphertext);

// InvalidKeySize for a key that is not 16, 24 or 32 bytes, InvalidNonceSize
// for an IV that is not 16, InvalidArgument for a ciphertext that is not whole
// blocks. With Pkcs7, a wrong key or altered data shows as DecryptionFailed -
// usually, not always: CBC has no tag, so a wrong key can produce plaintext
// that happens to end in valid padding. Only a MAC tells for certain. The
// output is empty on every failure.
UltraCryptResult UltraCrypt_AesCbcDecrypt(const UltraCryptSecureBuffer& key,
                                          const UltraCryptCbcParams& params,
                                          const void* ciphertext, size_t size,
                                          UltraCryptSecureBuffer& outPlaintext);

// ============================================================================
// AES-CTR (interop only)
// ============================================================================
// AES in counter mode (NIST SP 800-38A), for formats defined elsewhere that
// are built on it - Matrix's encrypted attachments and room-key export files,
// WebCrypto's AES-CTR. Like CBC it has no integrity of its own: the formats
// that use it carry an HMAC or a hash of the ciphertext, and the rule of the
// CBC section applies - check that BEFORE decrypting. Unlike CBC it needs no
// padding (the ciphertext is as long as the plaintext), so there is no
// padding oracle; but a counter block reused under one key gives away the XOR
// of the two plaintexts, so every message needs its own IV.
//
// The 16-byte IV is the first counter block; each next block adds one to it
// as a 128-bit big-endian number. A format that limits the counter to its low
// 64 bits (WebCrypto's `length: 64`, which Matrix uses) gets the same bytes
// as long as the counter does not reach 2^64 blocks - Matrix clears bit 63 of
// the IV so that it never can.
struct UltraCryptCtrParams {
    // Encrypt: if empty, a fresh random IV is generated and written back here
    // - the caller must store it. A format that wants a particular shape of
    // IV (Matrix: random with bit 63 clear) supplies its own.
    // Decrypt: must be the IV used at encryption.
    std::vector<uint8_t> iv;
};

// The ciphertext is exactly as long as the plaintext. InvalidKeySize for a
// key that is not 16, 24 or 32 bytes, InvalidNonceSize for an IV that is not
// 16 bytes.
UltraCryptResult UltraCrypt_AesCtrEncrypt(const UltraCryptSecureBuffer& key,
                                          UltraCryptCtrParams& params,
                                          const void* plaintext, size_t size,
                                          std::vector<uint8_t>& outCiphertext);

// Never fails on a wrong key or altered data - CTR cannot tell; check the
// format's MAC or hash first. The output is empty on every failure.
UltraCryptResult UltraCrypt_AesCtrDecrypt(const UltraCryptSecureBuffer& key,
                                          const UltraCryptCtrParams& params,
                                          const void* ciphertext, size_t size,
                                          UltraCryptSecureBuffer& outPlaintext);

// ============================================================================
// Key derivation
// ============================================================================
// One KDF. Argon2id is memory-hard, is the current standard (RFC 9106) and is
// what every UltraCanvas format and store uses. No alternative is offered for
// what UltraCanvas writes itself: a second KDF would be a second code path in
// every reader for no benefit. (PBKDF2, below, exists only to read and write
// formats defined elsewhere, as AES-CBC and AES-CTR do.)
enum class UltraCryptKdfAlgorithm : uint8_t {
    Argon2id
};

size_t UltraCrypt_GetKdfSaltSize();     // 16

struct UltraCryptKdfParams {
    UltraCryptKdfAlgorithm algorithm = UltraCryptKdfAlgorithm::Argon2id;

    // If empty, UltraCrypt_DeriveKeyFromPassword generates a random salt of
    // UltraCrypt_GetKdfSaltSize() bytes and writes it back — the caller stores
    // it alongside the ciphertext.
    std::vector<uint8_t> salt;

    uint32_t iterations   = 0;   // Argon2id passes ("opslimit")
    uint32_t memoryKiB    = 0;   // Argon2id memory cost
    uint32_t parallelism  = 1;   // Argon2id lanes. The backing implementation
                                 // fixes this at 1; any other value is
                                 // rejected rather than silently ignored, so
                                 // stored parameters always mean what they say.
    size_t   outputLength = 32;
};

// Current-guidance cost parameters: 3 passes, 64 MiB, parallelism 1. These are
// revisited as hardware moves, so stored data must always record the parameters
// it was written with rather than assuming today's defaults — otherwise raising
// the defaults orphans every existing file.
UltraCryptKdfParams UltraCrypt_RecommendedKdfParams(
        UltraCryptKdfAlgorithm algorithm = UltraCryptKdfAlgorithm::Argon2id);

UltraCryptResult UltraCrypt_DeriveKeyFromPassword(
        const UltraCryptSecureBuffer& password,
        UltraCryptKdfParams& params,
        UltraCryptSecureBuffer& outKey);

// HKDF (RFC 5869) — derives subkeys from existing high-entropy key material.
// NOT for passwords: it is deliberately fast, with no memory hardness. Use
// UltraCrypt_DeriveKeyFromPassword for anything a human typed.
//
// `salt` and `info` may be empty. SHA1 is rejected here — HKDF has no
// compatibility constraint forcing it.
UltraCryptResult UltraCrypt_DeriveKeyHkdf(
        UltraCryptHashAlgorithm algorithm,
        const UltraCryptSecureBuffer& inputKeyMaterial,
        const std::vector<uint8_t>& salt,
        const std::vector<uint8_t>& info,
        size_t outputLength,
        UltraCryptSecureBuffer& outKey);

// PBKDF2 (RFC 8018) - INTEROP ONLY, for formats defined elsewhere that
// derive their key with it: Matrix's room-key export files and secret
// storage passphrases (PBKDF2-HMAC-SHA-512), and the like. It is not
// memory-hard, so a GPU tries passwords against it far faster than against
// Argon2id: never use it for anything UltraCanvas defines - that is
// UltraCrypt_DeriveKeyFromPassword. SHA1 is rejected; SHA256 and SHA512 are
// offered. `iterations` is the format's (at least 1); `salt` may be empty.
UltraCryptResult UltraCrypt_DeriveKeyPbkdf2(
        UltraCryptHashAlgorithm algorithm,
        const UltraCryptSecureBuffer& password,
        const std::vector<uint8_t>& salt,
        uint32_t iterations,
        size_t outputLength,
        UltraCryptSecureBuffer& outKey);

