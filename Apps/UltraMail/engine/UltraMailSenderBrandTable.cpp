const std::vector<BrandRule>& SenderBrandRules() {
    static const std::vector<BrandRule> rules = [] {
        std::vector<BrandRule> v = BuildRules();
        for (BrandRule& rule : v) {
            if (!rule.brand.iconUrl.empty() || rule.domains.empty()) continue;
            const std::string& d = rule.domains.front();
            const bool apex = d.find('.') == d.rfind('.');   // "chase.com", not "x.co.uk"
            rule.brand.iconUrl = "https://" + std::string(apex ? "www." : "") + d + "/favicon.ico";
        }
        return v;
    }();
    return rules;
}

