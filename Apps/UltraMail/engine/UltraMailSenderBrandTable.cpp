// Apps/UltraMail/engine/UltraMailSenderBrandTable.cpp
// The known-sender registry's data: the brands an inbox actually hears from,
// and - because the threat scan reasons about the same table - the brands
// phishing mail most often dresses up as: banks and brokers, payment services,
// crypto exchanges and wallets, online shops and marketplaces, parcel
// carriers, social networks, cloud, hosting and file-sharing services, domain
// registrars, tax and government agencies, telecoms, game stores and security
// software.
//
// Rules for an entry, because a wrong one is worse than a missing one:
//  * A domain goes in only when it is the brand's own. A domain here is
//    *trusted*: mail from it gets the brand's name, icon and the blue
//    "business contact" badge, so a guessed or lapsed domain would hand that
//    to whoever registers it.
//  * Country domains are listed one by one rather than through `labels`,
//    which would trust a squatted lidl.xyz as Lidl.
//  * A name that is also an ordinary word is NameClaim::KeywordsOnly, with
//    keywords specific enough not to occur in ordinary mail ("chase bank",
//    not "chase").
//  * No keyword may be a mailbox provider's name ("outlook", "gmail",
//    "icloud"): a display name that is just the sender's own address
//    ("jane@outlook.com") would then claim the brand.
//  * A brand whose real mail comes from hundreds of regional domains
//    (Sparkasse) is recognised but not claimed, so its genuine mail is not
//    flagged as impersonation.
//
// Version: 0.1.1 - Amazon, eBay, Google and DHL list their country domains
//                  instead of trusting their name under any suffix
// Version: 0.1.0 - split out of UltraMailSenderBrands.cpp; ~400 brands
// Author: UltraCanvas Framework / ULTRA OS
