#!/usr/bin/env python3
# UltraAI/tests/make_tiny_llama_gguf.py
# Writes the GGUF fixture the llama.cpp adapter test runs on: a one-layer
# llama with a 259-token byte-fallback vocabulary, random weights from a
# fixed seed, and Gemma's chat template, ~140 KB. It is generated, not
# downloaded, so the test needs no network and no hosted model, and CI runs
# the adapter for real instead of compile-checking it.
#
# The weights are random, so the model says nothing sensible; what the test
# checks is the adapter: templating, the same-role turn merge, greedy
# generation, streaming, token counting, grammar-constrained JSON and pooled
# embeddings. Two output rows are set so that greedy decoding can never pick
# the end-of-sequence token: the rows of 'a' and 'b' are +100u and -100u for
# one random direction u, so max(logit_a, logit_b) = 100|h.u| > 0 = logit_eos
# whatever the hidden state h, while every other row is small noise. A reply
# is therefore always 32 tokens of a's and b's, deterministic on one machine.
#
# Usage: make_tiny_llama_gguf.py --gguf-py <llama.cpp>/gguf-py --output tiny.gguf
# Needs numpy (gguf-py's own dependency); the gguf package is taken from the
# llama.cpp checkout the adapter is built from, so the file matches the
# engine that reads it.
# Version: 0.1.0
# Last Modified: 2026-11-12
# Author: UltraAI Module

import argparse
import sys
from pathlib import Path

import numpy as np

# Gemma's template, the one that refuses two user turns in a row on a server
# that renders Jinja ("Conversation roles must alternate user/assistant/
# user/assistant/..."). llama.cpp's built-in renderer recognises it by the
# <start_of_turn> marker and renders it without a Jinja engine.
GEMMA_CHAT_TEMPLATE = (
    "{{ bos_token }}"
    "{% if messages[0]['role'] == 'system' %}"
    "{{ raise_exception('System role not supported') }}{% endif %}"
    "{% for message in messages %}"
    "{% if (message['role'] == 'user') != (loop.index0 % 2 == 0) %}"
    "{{ raise_exception('Conversation roles must alternate "
    "user/assistant/user/assistant/...') }}{% endif %}"
    "{% if (message['role'] == 'assistant') %}{% set role = 'model' %}"
    "{% else %}{% set role = message['role'] %}{% endif %}"
    "{{ '<start_of_turn>' + role + '\\n' + message['content'] | trim + "
    "'<end_of_turn>\\n' }}{% endfor %}"
    "{% if add_generation_prompt %}{{'<start_of_turn>model\\n'}}{% endif %}"
)

N_EMBD = 32
N_HEAD = 2
N_FF = 64
N_CTX = 256
SEED = 20261112


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gguf-py", required=True, type=Path,
                        help="the gguf-py directory of a llama.cpp checkout")
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    sys.path.insert(0, str(args.gguf_py))
    import gguf  # noqa: E402  (from the llama.cpp checkout)

    rng = np.random.default_rng(SEED)

    def noise(*shape):
        return (rng.standard_normal(shape) * 0.02).astype(np.float32)

    # Byte-fallback SentencePiece vocabulary: <unk>, <s>, </s>, <0x00>..<0xFF>.
    tokens = ["<unk>", "<s>", "</s>"] + [f"<0x{i:02X}>" for i in range(256)]
    types = ([gguf.TokenType.UNKNOWN, gguf.TokenType.CONTROL,
              gguf.TokenType.CONTROL] + [gguf.TokenType.BYTE] * 256)
    scores = [0.0] * len(tokens)
    n_vocab = len(tokens)
    head_dim = N_EMBD // N_HEAD

    w = gguf.GGUFWriter(str(args.output), "llama")
    w.add_name("UltraAI tiny test llama")
    w.add_description("Random one-layer llama for the UltraAI llama.cpp "
                      "adapter test; generated by make_tiny_llama_gguf.py")
    w.add_context_length(N_CTX)
    w.add_embedding_length(N_EMBD)
    w.add_block_count(1)
    w.add_feed_forward_length(N_FF)
    w.add_head_count(N_HEAD)
    w.add_head_count_kv(N_HEAD)
    w.add_rope_dimension_count(head_dim)
    w.add_layer_norm_rms_eps(1e-5)
    w.add_vocab_size(n_vocab)
    w.add_file_type(gguf.LlamaFileType.ALL_F32)

    w.add_tokenizer_model("llama")
    w.add_token_list(tokens)
    w.add_token_types(types)
    w.add_token_scores(scores)
    w.add_bos_token_id(1)
    w.add_eos_token_id(2)
    w.add_unk_token_id(0)
    w.add_add_bos_token(True)
    w.add_chat_template(GEMMA_CHAT_TEMPLATE)

    # numpy shapes are the reverse of ggml's: (rows, n_embd) here is
    # {n_embd, rows} in the loader.
    w.add_tensor("token_embd.weight", noise(n_vocab, N_EMBD))
    w.add_tensor("output_norm.weight", np.ones(N_EMBD, dtype=np.float32))
    output = noise(n_vocab, N_EMBD)
    direction = rng.standard_normal(N_EMBD).astype(np.float32)
    direction /= np.linalg.norm(direction)
    output[ord("a") + 3] = 100.0 * direction
    output[ord("b") + 3] = -100.0 * direction
    output[2] = 0.0                       # </s>: never the greedy pick
    w.add_tensor("output.weight", output)
    w.add_tensor("blk.0.attn_norm.weight", np.ones(N_EMBD, dtype=np.float32))
    w.add_tensor("blk.0.attn_q.weight", noise(N_EMBD, N_EMBD))
    w.add_tensor("blk.0.attn_k.weight", noise(N_EMBD, N_EMBD))
    w.add_tensor("blk.0.attn_v.weight", noise(N_EMBD, N_EMBD))
    w.add_tensor("blk.0.attn_output.weight", noise(N_EMBD, N_EMBD))
    w.add_tensor("blk.0.ffn_norm.weight", np.ones(N_EMBD, dtype=np.float32))
    w.add_tensor("blk.0.ffn_gate.weight", noise(N_FF, N_EMBD))
    w.add_tensor("blk.0.ffn_up.weight", noise(N_FF, N_EMBD))
    w.add_tensor("blk.0.ffn_down.weight", noise(N_EMBD, N_FF))

    w.write_header_to_file()
    w.write_kv_data_to_file()
    w.write_tensors_to_file()
    w.close()
    print(f"wrote {args.output} ({args.output.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
